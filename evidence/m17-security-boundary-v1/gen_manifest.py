#!/usr/bin/env python3
"""Generate `HASHES.txt` for the M17 security-boundary workstream. Committed so the manifest is
re-derivable by a reader, which is the property PR #35's evidence package was audited for.

Run from the repository root, after every recorded file exists and before anything is committed:

    python3 evidence/m17-security-boundary-v1/gen_manifest.py

Rules, stated because a manifest whose scope is inferred is how finding F-2 began:

  * the base is `main` at BASE below — not `HEAD`. A HEAD-relative diff loses earlier commits'
    paths out of the scope the moment a second commit exists (observed on another branch: 55
    records fell to 51, then came back).
  * a manifest never records itself;
  * generated bytecode is out of scope by rule, so it is reported as an assertion, not hashed —
    a `.pyc` cannot be re-derived byte-for-byte by anyone else (its header carries the source mtime);
  * a "this file is absent / this is drift" note is never written as a `<path> <size> <64hex>`
    triple, because the verification recipe selects exactly that shape;
  * every number is measured here, at run time, not transcribed from a report.
"""

from __future__ import annotations

import datetime
import hashlib
import pathlib
import subprocess
import sys

BASE = "52f682c8435956c8210b3189cad23ebea973d2de"      # main, the base of this branch
EVID = "evidence/m17-security-boundary-v1"
SELF = f"{EVID}/HASHES.txt"
AWK = "awk 'NF==3 && length($3)==64 {print $3\"  \"$1}'"


def die(msg: str) -> None:
    raise SystemExit(f"gen_manifest: {msg}")


if not pathlib.Path("docs/architecture/roadmap.json").exists():
    die("run from the repository root")


def hb(path: str):
    b = pathlib.Path(path).read_bytes()
    return len(b), hashlib.sha256(b).hexdigest()


def blob_at(rev: str, path: str):
    r = subprocess.run(["git", "show", f"{rev}:{path}"], capture_output=True)
    if r.returncode != 0:
        return None
    return len(r.stdout), hashlib.sha256(r.stdout).hexdigest()


def git(*args: str) -> str:
    r = subprocess.run(["git", *args], capture_output=True, text=True, check=True)
    return r.stdout


now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

# A — every path this branch adds or modifies, measured against main.
status = git("diff", "--name-status", BASE).split("\n")
added, modified = [], []
for line in status:
    parts = line.split("\t")
    if len(parts) == 2 and parts[0] in ("A", "M") and parts[1] != SELF:
        (added if parts[0] == "A" else modified).append(parts[1])
    elif len(parts) == 3:                              # a rename would need both names
        die(f"unexpected diff entry {line!r}: this manifest does not cover renames")
if git("diff", "--name-status", BASE).count("D\t") and any(
    l.startswith("D\t") for l in status
):
    die("a path was deleted: record it as an assertion, not as a hash — extend this script first")

# B — the whole evidence directory, as the branch leaves it.
evid = sorted(
    p.as_posix() for p in pathlib.Path(EVID).rglob("*")
    if p.is_file() and "__pycache__" not in p.as_posix() and not p.name.endswith(".pyc")
    and p.as_posix() != SELF
)

# Bytecode: asserted absent from what this workstream adds, never hashed.
tracked_pyc = [l for l in git("ls-files").split("\n") if l.endswith(".pyc")]
new_pyc = [p for p in pathlib.Path(EVID).rglob("*.pyc")]

lines = [
    "Artifact identities — M17 security-boundary workstream, branch `docs/m17-security-boundary-analysis`.",
    "",
    f"Generated {now} by `{EVID}/gen_manifest.py`, from the working tree, after every file recorded here",
    "was written and before the commit that carries this file.",
    "",
    f"Base: `main` at `{BASE}` (PR #35's merge commit). This branch adds no change to any production",
    "path: the diff below is documentation, one test module, this evidence directory, and a `notes`",
    "string inside `docs/architecture/roadmap.json`.",
    "",
    "Verify from the repository root (mawk has no {64} intervals, so the length test is written this way):",
    f"    {AWK} {SELF} | sha256sum -c -",
    "",
    f"Scope, in numbers this script measured: {len(added)} added paths, {len(modified)} modified paths,",
    f"and the complete contents of `{EVID}/` ({len(evid)} files, this manifest excluded because it",
    "cannot record its own bytes).",
    "",
    "The files of this directory appear twice — once as a path this branch adds, once as a member of",
    "the package — so the record count exceeds the distinct-path count on purpose: section A is the",
    "branch delta and section C is the package. Both are things a reader may want to check separately.",
    "",
    "=== A — paths this branch adds, against main ===",
]
for f in added:
    n, h = hb(f)
    lines.append(f"{f} {n} {h}")

lines += ["", "=== B — paths this branch modifies (new identity; old identity is section D) ==="]
for f in modified:
    n, h = hb(f)
    lines.append(f"{f} {n} {h}")

lines += [
    "",
    "=== C — the complete evidence directory of this workstream, as committed ===",
]
for f in evid:
    n, h = hb(f)
    lines.append(f"{f} {n} {h}")

lines += ["", "=== D — the one pre-existing file this branch edits, old identity and new ==="]
for f in modified:
    old = blob_at(BASE, f)
    n, h = hb(f)
    if old:
        lines.append(
            f"# {f}: at {BASE[:12]} bytes={old[0]} sha256={old[1]}  ->  now bytes={n} sha256={h}"
        )

lines += [
    "",
    "=== E — assertions that have no bytes to hash ===",
    f"# no production path is touched: `git diff --name-only {BASE[:12]} HEAD -- tools boot kernel psm src firmware`",
    "#   is empty (measured; see VERIFICATION log section 8);",
    f"# bytecode: {len(new_pyc)} generated files inside `{EVID}/` (none allowed, so none recorded), and",
    f"#   `git ls-files | grep '\\.pyc$'` returns {len(tracked_pyc)} path(s) in this tree. That number is",
    "#   inherited, not caused: `main` at the base commit still tracks",
    "#   evidence/usb-descriptor-remediation-v2/__pycache__/mutation_harness_v2.cpython-311.pyc, and",
    "#   PR #36 removes it. This branch deliberately does not duplicate that removal — it would collide",
    "#   with an open PR whose scope it is. Whichever lands second keeps the other's result.",
    "# the `notes` edit to roadmap.json changes no `state` field; M17, M18, M19, M20, M21 remain blocked,",
    "#   which is asserted by tests/test_milestone_deliverables.py and by the presentation gate's",
    "#   `13 status rows match roadmap.json` check.",
    "",
    "=== F — historical manifests this workstream did not touch, and how they read here ===",
    "# evidence/usb-descriptor-remediation-v2/HASHES-PR-TIP.txt and CORRECTED-MANIFEST.txt describe main",
    "#   at PR #35's tip. On THIS branch they verify completely, because this branch does not edit the",
    "#   two documents PR #36 edits. On PR #36's branch they each report exactly 2 failures. Both",
    "#   readings are correct, and neither file was regenerated here.",
]

pathlib.Path(SELF).write_text("\n".join(lines) + "\n")
print(f"written: {len(lines)} lines; A={len(added)} B={len(modified)} C={len(evid)} "
      f"tracked-pyc={len(tracked_pyc)} new-pyc={len(new_pyc)}")
